/* Generates docs/INSIGHT_CATALOGUE.md from the live catalogue so the docs cannot drift from the code.
   Run: node tools/gen-docs.js */
const fs = require('fs'), path = require('path'), vm = require('vm');
const DIR = path.join(__dirname, '..');
const ctx = { console, Math, JSON, Object, Array, String, Number, Date }; ctx.window = ctx; vm.createContext(ctx);
['core-logic.js', 'profile-schema.js', 'intelligence-engine.js'].forEach(f => vm.runInContext(fs.readFileSync(path.join(DIR, f), 'utf8') + '\n;', ctx, { filename: f }));
vm.runInContext('this.X = { PsycheIntelligence, DIMS }', ctx);
const { PsycheIntelligence: PI, DIMS } = ctx.X;
const name = k => { const p = k.split('.'); return DIMS[p[0]].facets[p[1]].name; };
let md = `# Insight catalogue — Profile dynamics (engine ${PI.engineVersion}, catalogue ${PI.catalogueVersion})

_Generated by \`node tools/gen-docs.js\` from \`intelligence-engine.js\`. Do not edit by hand._

## How a rule fires
- A facet is **high** at ${PI.thresholds.high}+ and **low** at ${PI.thresholds.low} or below. Anything between is the middle range, where a rule stays silent (no filler text).
- A rule has four defined states (hi-hi, hi-lo, lo-hi, lo-lo). Each state has its own interpretation and a set of signed *claims* used to detect contradictions between surfaced insights.
- Confidence measures support for the *inference*, not how strong the trait is. It is capped at "limited" when a score is within 3 points of a cut-off, when answers behind a facet disagree, when questions were skipped, or when answer-level evidence is missing. It is never "high" (two items per facet, no validation study).
- The engine abstains entirely for straight-lined responses or more than 7 skipped questions.
- Budget: up to ${PI.budget.primary} insights shown, ${PI.budget.max - PI.budget.primary} more on request; one per theme; a facet is used at most twice.
- Every generated string is linted for diagnostic or deterministic language before it can be shown.

`;
PI.catalogue().forEach(r => {
  md += `## ${r.title} — \`${r.id}\`\n\n- **Theme:** ${r.theme}\n- **Facets:** ${r.keys.map(k => name(k) + ' (`' + k + '`)').join(' × ')}\n- **Rationale:** ${r.rationale}\n- **Counterexample:** ${r.counterexample}\n- **Limits:** ${r.limits}\n`;
  md += '- **Other explanations:**\n' + r.alternatives.map(a => '  - ' + a).join('\n') + '\n';
  md += `- **Experiment (${r.action.window}):** ${r.action.text}\n- **Success signal:** ${r.action.success}\n\n| State | Claims | Interpretation |\n|---|---|---|\n`;
  r.states.forEach(s => { md += `| ${s.state} | ${s.claims.join(', ')} | ${s.text.replace(/\|/g, '\\|')} |\n`; });
  md += '\n';
});
md += `## Tests that guard this catalogue
- \`tests/intelligence-engine.test.js\`: determinism, stable IDs, abstention, confidence rules, evidence traceability, a 2,500-profile sweep for duplicate themes/texts, facet reuse, contradictory claims and unsafe language; every catalogue field is linted; all four states exist for every rule.
- \`tests/eval.test.js\`: the fixed evaluation set (\`tests/fixtures/eval-profiles.json\`) with reviewed expected properties.
- \`tests/integration.test.js\`: the card renders tiers, the why-panel, abstention and local feedback.
`;
fs.writeFileSync(path.join(DIR, '..', 'docs', 'INSIGHT_CATALOGUE.md'), md);
console.log('wrote docs/INSIGHT_CATALOGUE.md (' + md.length + ' chars)');
